#!/usr/bin/env bash
# Builds the single-file, tool-neutral edition of the bailiwick-sage500 skill
# from the Claude skill folder, so the two never drift apart.
#   usage: bash skills/build-portable.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
src="$here/bailiwick-sage500"
out="$here/bailiwick-sage500-portable.md"

# Reference file names become part names inside the single file.
relink() {
  sed -e 's#`references/data-model.md`#Part 2, "Data model"#g' \
      -e 's#`references/custom-objects.md`#Part 3, "Custom objects"#g' \
      -e 's#`references/fusion-conversion.md`#Part 4, "Fusion conversion"#g' \
      -e 's#`references/retirement.md`#Part 5, "Retirement"#g' \
      -e 's#`references/queries.sql`#Part 6, "Query library"#g' \
      -e 's#`data-model.md`#Part 2#g' \
      -e 's#`custom-objects.md`#Part 3#g' \
      -e 's#`fusion-conversion.md`#Part 4#g' \
      -e 's#`retirement.md`#Part 5#g' \
      -e 's#`queries.sql`#Part 6#g'
}

{
  cat <<'EOF'
<!-- Generated by skills/build-portable.sh from skills/bailiwick-sage500/. Edit the sources, then rebuild. -->

# Bailiwick Sage 500 knowledge pack (portable edition)

**What this is.** Working knowledge of Bailiwick's Sage 500 ERP database (`MAS500_app`), written for
the Oracle Fusion finance conversion and the retirement of Sage. It is plain Markdown and T-SQL with
no dependency on any one assistant or tool.

**How to use it.**

- *With an AI assistant:* give this whole file as system instructions, project knowledge, a custom
  instruction file or an attached document. Tell the assistant how it reaches the database (any SQL
  Server client, or a query tool it has been given).
- *As a person:* read Part 1, then go to the part that fits the task. Part 6 is runnable SQL.
- *With Claude:* use the packaged skill in `skills/bailiwick-sage500/` instead; it carries the same
  content split into files that load on demand.

**Parts.** 1 Core rules · 2 Data model · 3 Custom objects · 4 Fusion conversion · 5 Retirement ·
6 Query library

**Instructions to an assistant reading this.** Treat Part 1 as rules. Before writing SQL, check the
table and column names in Part 2 or against the live catalog. Prefer adapting a query from Part 6 to
writing one from nothing. Figures in this document describe the 2026-11-13 snapshot; re-run the query
before a decision rests on a number. Never output passwords, bank account numbers or taxpayer IDs.

---

# Part 1. Core rules

EOF
  # SKILL.md without its YAML front matter and without its own title line
  awk 'BEGIN{fm=0} /^---[[:space:]]*$/ {fm++; next} fm>=2' "$src/SKILL.md" | sed '/^# Bailiwick Sage 500 (MAS500_app)$/d' | relink

  printf '\n---\n\n# Part 2. Data model\n\n'
  sed '1d' "$src/references/data-model.md" | relink
  printf '\n---\n\n# Part 3. Custom objects\n\n'
  sed '1d' "$src/references/custom-objects.md" | relink
  printf '\n---\n\n# Part 4. Fusion conversion\n\n'
  sed '1d' "$src/references/fusion-conversion.md" | relink
  printf '\n---\n\n# Part 5. Retirement\n\n'
  sed '1d' "$src/references/retirement.md" | relink
  printf '\n---\n\n# Part 6. Query library\n\n```sql\n'
  cat "$src/references/queries.sql"
  printf '```\n'
} > "$out"

echo "wrote $out ($(wc -l < "$out") lines)"
